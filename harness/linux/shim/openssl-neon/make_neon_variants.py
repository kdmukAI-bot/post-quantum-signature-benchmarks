#!/usr/bin/env python3
"""
Generates the two NEON source files of the Pi Zero 2 W builds (COMPRESS=asmneon and
COMPRESS=asmneonbe in harness/linux/Makefile) from shim/openssl-armv4/sha256-armv4.S, which is
OpenSSL 3.4.1's crypto/sha/asm/sha256-armv4.pl output for the linux32 flavour
(regenerating it from the perlasm gives the same file byte for byte).

That one generated file holds three block functions, selected when it is assembled:
the integer code, the NEON code (sha256_block_data_order_neon, assembled when
__ARM_MAX_ARCH__ is 7 or more), and the ARMv8 cryptographic-extension code. With
__ARM_MAX_ARCH__ 7, the integer entry point also reads OPENSSL_armcap_P and jumps to the
NEON or ARMv8 code at run time. The files written here keep only the K256 table and the
NEON function, so the NEON code is called directly, with no capability check:

  sha256-neon.S     the NEON function unchanged (state in native word order, any number
                    of blocks), renamed at assembly time to pqb_sha256_blocks
  sha256-neon-be.S  a single-block drop-in sha2_256_compress(void *v) for slhdsa-c, as
                    make_be_variant.py does for the integer code: the block is at v + 32,
                    and the eight state words are byte-swapped after they are loaded and
                    before they are stored, because slhdsa-c keeps them as big-endian
                    bytes; the 64 rounds, the NEON message schedule, and the K256 table
                    are OpenSSL's code unchanged

Each change is anchored on exact text of OpenSSL's output; the script stops if an anchor
is missing or ambiguous.

Usage: make_neon_variants.py sha256-armv4.S OUT_DIR
"""
import os
import sys


def replace_once(text, old, new):
    n = text.count(old)
    if n != 1:
        sys.exit(f"anchor found {n} times, expected once:\n{old}")
    return text.replace(old, new)


def section(text, start, end):
    """Text from the line that starts with START up to and including the line END."""
    i = text.index(start)
    if text.count(start) != 1:
        sys.exit(f"start anchor not unique: {start!r}")
    j = text.index(end, i) + len(end)
    return text[i:j]


HEADER = """@ Generated by harness/linux/shim/openssl-neon/make_neon_variants.py from
@ harness/linux/shim/openssl-armv4/sha256-armv4.S (OpenSSL 3.4.1 crypto/sha/asm/sha256-armv4.pl,
@ linux32 flavour). {what}
@ Do not edit; edit the generator instead.
@
"""


def main():
    src, out_dir = sys.argv[1], sys.argv[2]
    s = open(src).read()

    # OpenSSL's copyright and credits: everything before the first preprocessor line.
    credits = s[: s.index("#ifndef __KERNEL__\n")]
    mode = section(s, "#if defined(__thumb2__)\n.syntax\tunified\n", "#endif\n")
    k256 = section(s, ".type\tK256,%object\n", ".word\t0\t\t\t\t@ terminator\n")
    neon = section(s, ".arch\tarmv7-a\n.fpu\tneon\n",
                   ".size\tsha256_block_data_order_neon,.-sha256_block_data_order_neon\n")

    def assemble(what, body):
        return (HEADER.format(what=what) + credits + mode + "\n.text\n\n" + k256
                + ".align\t5\n" + body)

    with open(os.path.join(out_dir, "sha256-neon.S"), "w") as f:
        f.write(assemble("The NEON block function only, unchanged.", neon))

    be = neon
    be = replace_once(
        be,
        "\tadd\tr2,r1,r2,lsl#6\t@ len to point at the end of inp\n",
        "\tadd\tr1,r0,#32\t\t@ pqb: the block follows the 8 state words\n"
        "\tadd\tr2,r0,#96\t\t@ pqb: end of the single block\n",
    )
    regs = ["r4", "r5", "r6", "r7", "r8", "r9", "r10", "r11"]
    load = "\tldmia\tr0,{r4,r5,r6,r7,r8,r9,r10,r11}\n"
    be = replace_once(
        be, load,
        load + "".join(f"\trev\t{r},{r}\t\t@ pqb: big-endian state word\n" for r in regs))

    # The final additions and the store of the new state. Flags from the earlier
    # "teq r1,r0" must survive this block (the conditional code after it reads them);
    # ldr, rev, add, and str leave them alone.
    old_tail = (
        "\tldr\tr0,[r2,#0]\n"
        "\tadd\tr4,r4,r12\t\t\t@ h+=Maj(a,b,c) from the past\n"
        "\tldr\tr12,[r2,#4]\n"
        "\tldr\tr3,[r2,#8]\n"
        "\tldr\tr1,[r2,#12]\n"
        "\tadd\tr4,r4,r0\t\t\t@ accumulate\n"
        "\tldr\tr0,[r2,#16]\n"
        "\tadd\tr5,r5,r12\n"
        "\tldr\tr12,[r2,#20]\n"
        "\tadd\tr6,r6,r3\n"
        "\tldr\tr3,[r2,#24]\n"
        "\tadd\tr7,r7,r1\n"
        "\tldr\tr1,[r2,#28]\n"
        "\tadd\tr8,r8,r0\n"
        "\tstr\tr4,[r2],#4\n"
        "\tadd\tr9,r9,r12\n"
        "\tstr\tr5,[r2],#4\n"
        "\tadd\tr10,r10,r3\n"
        "\tstr\tr6,[r2],#4\n"
        "\tadd\tr11,r11,r1\n"
        "\tstr\tr7,[r2],#4\n"
        "\tstmia\tr2,{r8,r9,r10,r11}\n"
    )

    def rev4(a):
        return "".join(f"\trev\t{r},{r}\t\t@ pqb: big-endian state word\n" for r in a)

    new_tail = (
        "\tldr\tr0,[r2,#0]\n"
        "\tadd\tr4,r4,r12\t\t\t@ h+=Maj(a,b,c) from the past\n"
        "\tldr\tr12,[r2,#4]\n"
        "\tldr\tr3,[r2,#8]\n"
        "\tldr\tr1,[r2,#12]\n"
        + rev4(["r0", "r12", "r3", "r1"]) +
        "\tadd\tr4,r4,r0\t\t\t@ accumulate\n"
        "\tadd\tr5,r5,r12\n"
        "\tadd\tr6,r6,r3\n"
        "\tadd\tr7,r7,r1\n"
        "\tldr\tr0,[r2,#16]\n"
        "\tldr\tr12,[r2,#20]\n"
        "\tldr\tr3,[r2,#24]\n"
        "\tldr\tr1,[r2,#28]\n"
        + rev4(["r0", "r12", "r3", "r1"]) +
        "\tadd\tr8,r8,r0\n"
        "\tadd\tr9,r9,r12\n"
        "\tadd\tr10,r10,r3\n"
        "\tadd\tr11,r11,r1\n"
        "@ pqb: the state goes back as big-endian bytes. The swapped registers would be\n"
        "@ wrong for a second block, but this variant is entered with exactly one.\n"
        + rev4(regs[:4]) + rev4(regs[4:]) +
        "\tstr\tr4,[r2],#4\n"
        "\tstr\tr5,[r2],#4\n"
        "\tstr\tr6,[r2],#4\n"
        "\tstr\tr7,[r2],#4\n"
        "\tstmia\tr2,{r8,r9,r10,r11}\n"
    )
    be = replace_once(be, old_tail, new_tail)

    with open(os.path.join(out_dir, "sha256-neon-be.S"), "w") as f:
        f.write(assemble(
            "Single-block NEON drop-in for slhdsa-c's\n"
            "@ sha2_256_compress(void *v): big-endian state at v, block at v + 32.", be))


if __name__ == "__main__":
    main()
