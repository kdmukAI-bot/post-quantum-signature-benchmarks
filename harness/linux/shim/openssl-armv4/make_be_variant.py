#!/usr/bin/env python3
"""
Generates sha256-armv4-be.S from sha256-armv4.S (OpenSSL 3.4.1 perlasm output): a copy
of OpenSSL's integer SHA-256 block function changed into a drop-in
sha2_256_compress(void *v) for slhdsa-c (COMPRESS=asmrevbe), so no C wrapper runs around
the assembly.

slhdsa-c passes one pointer to eight big-endian state words followed by the 64-byte
block. The changes, each anchored on exact text of OpenSSL's output (the script stops if
any anchor is missing or ambiguous):
  1. Entry: the block is at v + 32 and there is exactly one block (instead of taking a
     block pointer and a block count).
  2. After the state is loaded (ldmia), eight rev instructions put it in native word
     order.
  3. Before the final additions, each reloaded state word gets a rev; before the state is
     stored (stmia), eight rev instructions put the result back in big-endian order.
Everything else (the 64 rounds, the K256 table, the message loads) is OpenSSL's code
unchanged. Only the integer code path is kept; the NEON and ARMv8 functions are dropped.

Usage: make_be_variant.py sha256-armv4.S sha256-armv4-be.S
"""
import sys


def replace_once(text, old, new):
    n = text.count(old)
    if n != 1:
        sys.exit(f"anchor found {n} times, expected once:\n{old}")
    return text.replace(old, new)


def main():
    src, dst = sys.argv[1], sys.argv[2]
    s = open(src).read()

    start = s.index(".text\n")
    end_marker = ".size\tsha256_block_data_order,.-sha256_block_data_order\n"
    end = s.index(end_marker) + len(end_marker)
    head = s[:start]
    body = s[start:end]

    body = replace_once(
        body,
        "\tadd\tr2,r1,r2,lsl#6\t@ len to point at the end of inp\n",
        "\tadd\tr1,r0,#32\t\t@ pqb: the block follows the 8 state words\n"
        "\tadd\tr2,r0,#96\t\t@ pqb: end of the single block\n",
    )
    regs = ["r4", "r5", "r6", "r7", "r8", "r9", "r10", "r11"]
    revs = "".join(f"\trev\t{r},{r}\t\t@ pqb: big-endian state word\n" for r in regs)
    load = "\tldmia\tr0,{r4,r5,r6,r7,r8,r9,r10,r11}\n"
    body = replace_once(body, load, load + revs)

    old_tail = (
        "\tldr\tr0,[r3,#0]\n"
        "\tldr\tr2,[r3,#4]\n"
        "\tldr\tr12,[r3,#8]\n"
        "\tadd\tr4,r4,r0\n"
        "\tldr\tr0,[r3,#12]\n"
        "\tadd\tr5,r5,r2\n"
        "\tldr\tr2,[r3,#16]\n"
        "\tadd\tr6,r6,r12\n"
        "\tldr\tr12,[r3,#20]\n"
        "\tadd\tr7,r7,r0\n"
        "\tldr\tr0,[r3,#24]\n"
        "\tadd\tr8,r8,r2\n"
        "\tldr\tr2,[r3,#28]\n"
        "\tadd\tr9,r9,r12\n"
        "\tldr\tr1,[sp,#17*4]\t\t@ pull inp\n"
        "\tldr\tr12,[sp,#18*4]\t\t@ pull inp+len\n"
        "\tadd\tr10,r10,r0\n"
        "\tadd\tr11,r11,r2\n"
        "\tstmia\tr3,{r4,r5,r6,r7,r8,r9,r10,r11}\n"
    )
    new_tail = []
    for line in old_tail.splitlines(keepends=True):
        parts = line.strip().split("\t")
        if parts[0] == "add" and parts[1].count(",") == 2:
            src_reg = parts[1].split(",")[2]
            new_tail.append(f"\trev\t{src_reg},{src_reg}\t\t@ pqb: big-endian state word\n")
        if parts[0] == "stmia":
            new_tail.append(revs.replace("big-endian state word", "back to big-endian"))
        new_tail.append(line)
    body = replace_once(body, old_tail, "".join(new_tail))

    note = (
        "@ pqb-sig-bench: generated by make_be_variant.py from the OpenSSL 3.4.1 perlasm\n"
        "@ output above. Single-block variant of sha256_block_data_order taking slhdsa-c's\n"
        "@ buffer (8 big-endian state words, then the block); see make_be_variant.py.\n"
        "@ Assemble with -Dsha256_block_data_order=sha2_256_compress.\n\n"
    )
    out = head + note + body
    out += '\n#if defined(__linux__) && defined(__ELF__)\n.section .note.GNU-stack,"",%progbits\n#endif\n'
    open(dst, "w").write(out)


if __name__ == "__main__":
    main()
