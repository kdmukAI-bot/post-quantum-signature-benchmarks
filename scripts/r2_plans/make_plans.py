#!/usr/bin/env python3
"""
Writes the round-2 run plans: pi0w.plan (scripts/r2_pi_queue.sh) and esp32s3.plan,
esp32p4.plan (scripts/r2_esp_queue.sh), in priority order:
(a) verification and lattice ops, (b) SHRINCS stateless signing at level 3, (c) memory pass
(Pi Zero W only), (d) round-1 ops with the round-2 builds, (e) stateless signing at levels 1
and 2. Run from this directory: python3 make_plans.py
"""
LAB = dict((
    ("1", ("soft-apidirect", "plain-c direct; gcc13.3 -O2")),
    ("2", ("openssl", "openssl; gcc13.3 -O2 openssl3.4.1")),
    ("3", ("asmrevbe-apinative-opto3-lto", "asmrevbe native; gcc13.3 -O3 -flto PIE")),
))
SWN = dict((("B", "2040"), ("L", "140")))
VERIFY = dict((("B", ["slh_dsa_verify", "sphincs40_verify", "xmss_verify", "shrincs_verify",
                      "shrincs_verify_stateless"]),
               ("L", ["shrincs_verify", "shrincs_verify_stateless"])))
LATTICE = []
for ps in ("44", "65", "87"):
    for var in ("", "_lowram"):
        for k in ("keygen", "sign", "verify"):
            LATTICE.append(f"mldsa{ps}{var}_{k}")
for n in ("512", "1024"):
    for k in ("keygen", "sign", "verify"):
        LATTICE.append(f"fndsa{n}_{k}")
R1 = dict((
    ("B", [("shrincs_selftest", 3, "2040"), ("xmss_selftest", 3, ""), ("slh_dsa_sign", 100, ""),
           ("sphincs40_sign", 100, ""), ("shrincs_sign", 100, "2040"), ("xmss_sign", 100, ""),
           ("slh_dsa_keygen", 100, ""), ("sphincs40_keygen", 100, ""),
           ("shrincs_keygen", 100, ""), ("xmss_keygen", 100, "")]),
    ("L", [("shrincs_selftest", 3, "140"), ("shrincs_sign", 100, "96"),
           ("shrincs_sign", 100, "140"), ("shrincs_keygen", 100, "")]),
))
SWN_OPS = set(("shrincs_verify", "shrincs_verify_stateless", "shrincs_sign",
               "shrincs_sign_stateless", "shrincs_selftest"))


def pi(lvl, v, mem=False):
    d, lab = LAB[lvl]
    return (f"r2-armv6-shrincs{v}-{d}{'-mem' if mem else ''}",
            f"r2-L{lvl}{'-mem' if mem else ''} shrincs-{v} {lab}")


def pline(lvl, v, op, n, swn="", mem=False):
    b, lab = pi(lvl, v, mem)
    if not swn and op in SWN_OPS:
        swn = SWN[v]
    return f"{b}|{lab}|{op}|{n}" + (f"|{swn}" if swn else "")


def pi_plan():
    out = ["# Round-2 run plan, Pi Zero W (scripts/r2_pi_queue.sh). Generated by",
           "# scripts/r2_plans/make_plans.py.", "#",
           "# (a) verification, every scheme, levels 3, 1, 2; lattice ops at levels 3 and 1"]
    for lvl in ("3", "1", "2"):
        for v in ("B", "L"):
            for op in VERIFY[v]:
                out.append(pline(lvl, v, op, 100))
        if lvl != "2":
            for op in LATTICE:
                out.append(pline(lvl, "B", op, 100))
    out.append("# (b) SHRINCS stateless signing, level 3 (over 30 s per run: n=10, a deviation)")
    for v in ("B", "L"):
        out.append(pline("3", v, "shrincs_sign_stateless", 10))
    out.append("# (c) peak memory (memory builds, not for timing), levels 3, 1, 2")
    for lvl in ("3", "1", "2"):
        for v in ("B", "L"):
            for op in VERIFY[v]:
                out.append(pline(lvl, v, op, 10, mem=True))
            for op, n, swn in R1[v]:
                nn = 1 if (op.endswith("selftest") or swn == "140") else 3
                out.append(pline(lvl, v, op, nn, swn, mem=True))
            out.append(pline(lvl, v, "shrincs_sign_stateless", 1, mem=True))
        if lvl != "2":
            for op in LATTICE:
                out.append(pline(lvl, "B", op, 10, mem=True))
    out.append("# (d) round-1 operations with the round-2 builds (reproducibility), levels 3, 1, 2")
    for lvl in ("3", "1", "2"):
        for v in ("B", "L"):
            for op, n, swn in R1[v]:
                out.append(pline(lvl, v, op, n, swn))
    out.append("# (e) SHRINCS stateless signing, levels 1 and 2 (n=10, a deviation)")
    for lvl in ("1", "2"):
        for v in ("B", "L"):
            out.append(pline(lvl, v, "shrincs_sign_stateless", 10))
    return out


def esp_plan(board):
    def b(lvl, v, dc):
        return f"build-{board}-r2-L{lvl}-{v}-dc{dc}"
    name = "Waveshare ESP32-S3 Touch LCD 2" if board == "s3" else "ESP32-P4"
    out = [f"# Round-2 run plan, {name} (scripts/r2_esp_queue.sh). Generated by",
           "# scripts/r2_plans/make_plans.py. Fields: build|set|n.",
           "# Peak stack and heap come with every row on the ESP32 boards, so there is no",
           "# separate memory pass (c).",
           "#", "# (a) verification in every build; lattice ops at levels 3 and 1 (one core)"]
    for lvl in ("3", "1", "2"):
        for dc in ("0", "1"):
            for v in ("B", "L"):
                out.append(f"{b(lvl, v, dc)}|verify|10")
                if v == "B" and dc == "0" and lvl != "2":
                    out.append(f"{b(lvl, v, dc)}|lattice|10")
    out.append("# (b) SHRINCS stateless signing, level 3, one core then two cores")
    for dc in ("0", "1"):
        for v in ("B", "L"):
            out.append(f"{b('3', v, dc)}|stateless|10")
    out.append("# (d) round-1 job lists with the round-2 builds (reproducibility)")
    for lvl in ("3", "1", "2"):
        for dc in ("0", "1"):
            for v in ("B", "L"):
                out.append(f"{b(lvl, v, dc)}|r1|10")
    out.append("# (e) SHRINCS stateless signing, levels 2 and 1")
    for lvl in ("2", "1"):
        for dc in ("0", "1"):
            for v in ("B", "L"):
                out.append(f"{b(lvl, v, dc)}|stateless|10")
    return out


if __name__ == "__main__":
    open("pi0w.plan", "w").write("\n".join(pi_plan()) + "\n")
    for board in ("s3", "p4"):
        open(f"esp32{board}.plan", "w").write("\n".join(esp_plan(board)) + "\n")
