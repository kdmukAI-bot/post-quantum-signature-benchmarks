#!/usr/bin/env python3
"""
Writes the round-3 run plans: esp32p4.plan and esp32s3.plan (scripts/r2_esp_queue.sh,
fields build|set|n) and pi0w.plan (scripts/r3_pi_queue.sh, fields
build|label|op|n[|swn]). Run from this directory: python3 make_plans.py

Round 3 changes only the harness's time format (%.4f to %.6f seconds) and reruns the
short job sets: verification everywhere, and the lattice operations at n=100 (inputs 0 to
99) on every board. The Pi Zero W plan is priority (a) of scripts/r2_plans/pi0w.plan with
each round-2 build ("r2-armv6-...") replaced by its round-3 rebuild ("r3-armv6-...") and
the label's "r2-" tag replaced by "r3-"; nothing else in those lines changes.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
R2_PI_PLAN = os.path.join(HERE, "..", "r2_plans", "pi0w.plan")


def esp_plan(board):
    name = "Waveshare ESP32-S3 Touch LCD 2" if board == "s3" else "ESP32-P4"

    def b(lvl, v):
        return f"build-{board}-r3-L{lvl}-{v}-dc0"
    out = [f"# Round-3 run plan, {name}. Generated by scripts/r3_plans/make_plans.py.",
           f"# Run with: scripts/r2_esp_queue.sh {board} scripts/r3_plans/esp32{board}.plan",
           f"#   results/raw/esp32{board}/r3",
           "# Fields: build|set|n. One-core builds only (round 2: one- and two-core",
           "# verification times agreed within 0.8%). Order: level 3, then 1, then 2.",
           "#",
           "# Level 3: verification in the SHRINCS-B and SHRINCS-L builds (n=10: messages 0",
           "# to 9 once each); lattice ops at n=100 in the SHRINCS-B build (keygen seeds and",
           "# signing messages 0 to 99; verification cycles through the ten embedded",
           "# signatures, as on the Pi Zero W)",
           f"{b(3, 'B')}|verify|10",
           f"{b(3, 'B')}|lattice|100",
           f"{b(3, 'L')}|verify|10",
           "# Level 1: the same three job sets",
           f"{b(1, 'B')}|verify|10",
           f"{b(1, 'B')}|lattice|100",
           f"{b(1, 'L')}|verify|10",
           "# Level 2: verification only (no SHA-3 hardware, so level 2 runs the level-1",
           "# lattice code)",
           f"{b(2, 'B')}|verify|10",
           f"{b(2, 'L')}|verify|10"]
    return out


def pi_plan():
    out = ["# Round-3 run plan, Pi Zero W. Generated by scripts/r3_plans/make_plans.py from",
           "# priority (a) of scripts/r2_plans/pi0w.plan: every line unchanged except the",
           "# build directory (r2-armv6-... -> r3-armv6-...) and the label's tag (r2-L<level>",
           "# -> r3-L<level>). Run on the Pi with scripts/r3_pi_queue.sh (via",
           "# scripts/r3_pi_deploy.sh). Fields: build|label|op|n[|swn].",
           "#"]
    in_a = False
    for ln in open(R2_PI_PLAN):
        ln = ln.rstrip("\n")
        if ln.startswith("# (a)"):
            in_a = True
            out.append("# (a) verification, every scheme, levels 3, 1, 2 (n=100: ten passes over the")
            out.append("# ten embedded signatures); lattice ops at levels 3 and 1, reduced-RAM ML-DSA")
            out.append("# included (n=100: keygen seeds and signing messages 0 to 99)")
            continue
        if ln.startswith("# (b)"):
            break
        if not in_a or not ln or ln.startswith("#"):
            continue
        f = ln.split("|")
        assert f[0].startswith("r2-armv6-") and f[1].startswith("r2-L"), ln
        f[0] = "r3-armv6-" + f[0][len("r2-armv6-"):]
        f[1] = "r3-" + f[1][len("r2-"):]
        out.append("|".join(f))
    return out


if __name__ == "__main__":
    for board in ("p4", "s3"):
        with open(os.path.join(HERE, f"esp32{board}.plan"), "w") as f:
            f.write("\n".join(esp_plan(board)) + "\n")
    with open(os.path.join(HERE, "pi0w.plan"), "w") as f:
        f.write("\n".join(pi_plan()) + "\n")
